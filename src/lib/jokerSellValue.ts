const JOKER_EDITION_COSTS: Record<JokerEdition, number> = {
	'Base': 0,
	'Foil': 2,
	'Holographic': 3,
	'Polychrome': 5,
	'Negative': 5,
}

/**
 * Sell value is half the joker's cost (base price plus edition surcharge), rounded down, with a minimum of $1.
 */
export function getJokerSellValue (joker: Pick<Joker, 'name' | 'edition'>): number {
	return Math.max(1, Math.floor((JOKER_COSTS[joker.name] + JOKER_EDITION_COSTS[joker.edition]) / 2))
}
