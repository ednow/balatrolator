import { writeFileSync } from 'node:fs'
import { pinyin } from 'pinyin-pro'

import { zhTerms } from '../src/ui/zh-terms.ts'

const options = { toneType: 'none', nonZh: 'consecutive' } as const

const quote = (value: string) => `'${value.replaceAll('\\', '\\\\').replaceAll('\'', '\\\'')}'`

const entries = [...new Set(Object.values(zhTerms))]
	.sort((a, b) => a.localeCompare(b, 'zh-CN'))
	.map((zh) => {
		const full = pinyin(zh, { ...options, type: 'array' }).join('').toLowerCase()
		const initials = pinyin(zh, { ...options, pattern: 'first', type: 'array' }).join('').toLowerCase()
		return `\t${quote(zh)}: { full: ${quote(full)}, initials: ${quote(initials)} },`
	})

const file = `// Generated by scripts/generate-pinyin.ts from zh-terms.ts using pinyin-pro.
// Re-run \`npm run generate:pinyin\` after changing the Chinese terms.
export const zhPinyin: Record<string, { full: string, initials: string }> = {
${entries.join('\n')}
}
`

writeFileSync(new URL('../src/ui/zh-pinyin.ts', import.meta.url), file)
